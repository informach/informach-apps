// Builds src/shared/lexicon/ptWords.ts, the Portuguese word list the glossary uses to never swap a
// real word for a look-alike name. Source: the 50,000 most frequent Brazilian Portuguese words of
// hermitdave/FrequencyWords (OpenSubtitles 2018), content under CC BY-SA 4.0, at a pinned commit
// and checked against its SHA-256. Words are folded (lowercase, no accents) and front-coded.
//
//   node scripts/build-pt-lexicon.mjs
import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const COMMIT = "525f9b560de45753a5ea01069454e72e9aa541c6";
const SOURCE = `https://raw.githubusercontent.com/hermitdave/FrequencyWords/${COMMIT}/content/2018/pt_br/pt_br_50k.txt`;
const SHA256 = "a61d6f2ede97c5daad5fb3907b72a228f0aff12668be6d24da590d20804fa611";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(app, "src", "shared", "lexicon", "ptWords.ts");

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`download failed (${res.status}) for ${SOURCE}`);
const bytes = Buffer.from(await res.arrayBuffer());
const digest = createHash("sha256").update(bytes).digest("hex");
if (digest !== SHA256) throw new Error(`unexpected SHA-256 ${digest} for ${SOURCE}`);

const fold = (s) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[^a-z0-9]/g, "");
const words = new Set();
for (const line of bytes.toString("utf8").split("\n")) {
  const word = line.split(" ")[0]?.trim();
  // Letters only: numbers, contractions with apostrophes and stray symbols are left out.
  if (!word || !/^\p{L}+$/u.test(word)) continue;
  const folded = fold(word);
  if (folded) words.add(folded);
}
const sorted = [...words].sort();

// Front coding: each entry is the length of the prefix it shares with the previous one (base 36,
// one character, at most 35) followed by the rest of the word.
let previous = "";
const coded = sorted.map((w) => {
  let shared = 0;
  while (
    shared < 35 &&
    shared < w.length &&
    shared < previous.length &&
    w[shared] === previous[shared]
  )
    shared++;
  previous = w;
  return shared.toString(36) + w.slice(shared);
});

const header = `// Generated by scripts/build-pt-lexicon.mjs. Do not edit by hand.
// ${sorted.length} Portuguese words, folded (lowercase, no accents), front-coded.
// Derived from hermitdave/FrequencyWords, pt_br_50k.txt at commit ${COMMIT}
// (word frequencies of the OpenSubtitles 2018 corpus). Content licensed under CC BY-SA 4.0
// (https://creativecommons.org/licenses/by-sa/4.0/); this derived list is shared under the same
// license. See src/shared/lexicon/LICENSE-pt-words.txt.
`;
await writeFile(out, `${header}export const PT_WORDS = "${coded.join(",")}";\n`);
console.log(`wrote ${sorted.length} words to ${out}`);

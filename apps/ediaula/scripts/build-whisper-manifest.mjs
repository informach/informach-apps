// Builds src/main/whisperManifest.ts: the SHA-256 and size of every file inside the pinned
// whisper.cpp engine zips (src/main/whisperAssets.ts). Each zip is downloaded, checked against
// the digest GitHub publishes for it and only then extracted and hashed, so the list comes from
// the official release. EdiAula uses it to check an engine already installed before downloads
// were checked, and every new install.
//
//   node scripts/build-whisper-manifest.mjs <empty work folder>
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { WHISPER_ASSETS } from "../src/main/whisperAssets.ts";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(app, "src", "main", "whisperManifest.ts");
const work = process.argv[2];
if (!work) throw new Error("usage: node scripts/build-whisper-manifest.mjs <empty work folder>");

const hashFile = async (path) => {
  const hash = createHash("sha256");
  for await (const chunk of createReadStream(path)) hash.update(chunk);
  return hash.digest("hex");
};

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else yield p;
  }
}

const manifest = {};
for (const [variant, asset] of Object.entries(WHISPER_ASSETS.engine)) {
  const zip = join(work, `${variant}.zip`);
  const res = await fetch(asset.url);
  if (!res.ok || !res.body) throw new Error(`download failed (${res.status}) for ${asset.url}`);
  await pipeline(Readable.fromWeb(res.body), createWriteStream(zip));
  const size = (await stat(zip)).size;
  const digest = await hashFile(zip);
  if (size !== asset.size || digest !== asset.sha256)
    throw new Error(`${asset.url} does not match the published digest`);
  const dir = join(work, variant);
  await mkdir(dir, { recursive: true });
  await promisify(execFile)("C:\\Windows\\System32\\tar.exe", ["-xf", zip, "-C", dir]);
  const files = {};
  for await (const file of walk(dir)) {
    const name = relative(dir, file).split("\\").join("/");
    files[name] = { sha256: await hashFile(file), size: (await stat(file)).size };
  }
  manifest[variant] = Object.fromEntries(
    Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)),
  );
  await rm(zip, { force: true });
  await rm(dir, { recursive: true, force: true });
  console.log(`${variant}: ${Object.keys(files).length} files`);
}

const body = Object.entries(manifest)
  .map(
    ([variant, files]) =>
      `  ${variant}: {\n${Object.entries(files)
        .map(
          ([name, f]) => `    ${JSON.stringify(name)}: { sha256: "${f.sha256}", size: ${f.size} },`,
        )
        .join("\n")}\n  },`,
  )
  .join("\n");
await writeFile(
  out,
  `// Generated by scripts/build-whisper-manifest.mjs from the engine zips of whisperAssets.ts,
// after checking each zip against its published digest. Do not edit by hand.
import type { WhisperVariant } from "../shared/types.ts";
import type { Expected } from "./download.ts";

export const ENGINE_FILES: Record<WhisperVariant, Record<string, Expected>> = {
${body}
};
`,
);
console.log(`wrote ${out}`);

const {chromium}=require('playwright');
(async()=>{const b=await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader']});
const p=await b.newPage({viewport:{width:1400,height:820}});
const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await p.goto('http://localhost:8765/teste_local.html');
await p.waitForFunction(()=>document.getElementById('status').textContent==='',{timeout:120000});
await p.waitForTimeout(1500);await p.screenshot({path:'v1.png'});
await p.click('button[data-tom="Escura"]');await p.waitForTimeout(800);await p.screenshot({path:'v2.png'});
await p.click('button[data-tom="Morena"]');await p.click('button[data-id="plus_f"]');await p.waitForTimeout(1500);await p.screenshot({path:'v3.png'});
const m=await b.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});await m.goto('http://localhost:8765/teste_local.html');
await m.waitForFunction(()=>document.getElementById('status').textContent==='',{timeout:120000});await m.waitForTimeout(1000);
await m.screenshot({path:'v4.png'});console.log('sw',await m.evaluate(()=>document.documentElement.scrollWidth),errs);await b.close();})();

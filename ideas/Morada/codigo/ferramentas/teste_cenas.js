const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const p = await b.newPage({ viewport: { width: 1400, height: 1000 } });
  const erros = [];
  const T = '/tmp/claude-0/-home-user-informach-apps/4b0c5cb8-e6f3-54e3-8b85-cd31fc21bb7f/scratchpad/rosto_viewer/_three/node_modules/three/';
  await p.route(/cdn\.jsdelivr\.net\/npm\/three@[^/]+\/(.*)$/, (r) => {
    const rel = r.request().url().replace(/^.*three@[^/]+\//, '');
    r.fulfill({ path: T + rel, contentType: 'application/javascript' });
  });
  const SPD = '/tmp/claude-0/-home-user-informach-apps/4b0c5cb8-e6f3-54e3-8b85-cd31fc21bb7f/scratchpad/';
  const TIPOS = { html: 'text/html; charset=utf-8', json: 'application/json', txt: 'text/plain', webp: 'image/webp', jpg: 'image/jpeg', png: 'image/png', js: 'application/javascript' };
  await p.route(/^http:\/\/localhost:8766\//, (r) => { const rel = decodeURIComponent(new URL(r.request().url()).pathname.slice(1)); r.fulfill({ path: SPD + rel, contentType: TIPOS[rel.split('.').pop()] || 'application/octet-stream' }); });
  await p.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.fulfill({ body: '', contentType: 'text/css' }));
  p.on('console', m => { if (m.type() === 'error') erros.push(m.text()); });
  p.on('pageerror', e => erros.push(String(e)));
  const S = process.env.SAIDA, pagina = process.argv[2] || '_teste_cenas/cidade.html', cena = process.argv[3];
  await p.goto('http://localhost:8766/' + pagina);
  await p.waitForTimeout(4000);
  console.log('erros0', JSON.stringify(erros));
  if (cena) await p.click(`#cena-chips [data-id="${cena}"]`);
  await p.click('#ir-cenas');
  await p.waitForTimeout(800);
  await p.locator('#cenas').screenshot({ path: S + '/c0.png' });
  await p.click('#cena-montar');
  await p.waitForFunction(() => document.getElementById('palco-cena').classList.contains('montada') || /Não foi/.test(document.getElementById('cena-carregando').textContent), null, { timeout: 600000 });
  await p.waitForTimeout(3000);
  await p.locator('#palco-cena').scrollIntoViewIfNeeded(); await p.screenshot({ path: S + '/c1.png', timeout: 300000 });
  await p.click('#cena-noite');
  await p.waitForTimeout(2500);
  await p.screenshot({ path: S + '/c2.png', timeout: 300000 });
  console.log('dados', await p.locator('#cena-dados').innerText());
  console.log('erros', JSON.stringify(erros));
  await b.close();
})();
